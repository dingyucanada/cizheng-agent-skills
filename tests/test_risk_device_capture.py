    assert after['dimensions'][0]['state'] == 'conflicting'
    assert after['indices']['conflict_index'] == 20
    assert digest(store.read('run', run['id'])) == original
    # Consecutive review-only mutations cannot silently remove the same conflict.
    response = check(c, case, 'style', 'consistent'); assert response.status_code == 201
    assert c.get('/api/cases/'+case['id']+'/risk-triage').json()['indices']['conflict_index'] == 20


