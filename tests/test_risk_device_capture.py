def saved_current_conflict(store, case):
    """A saved software fixture, never a model invocation or expert label."""
    run = {'id': uid('run'), 'case_id': case['id'], 'case_revision': case['revision'],
           'state': 'ready', 'reference_snapshot': [],
           'observations': [{'id': 'fixture-obs', 'media_id': case['media'][0]['id'], 'region': [0, 0, 1, 1]}],
           'assessment': {'claims': [{'dimension': 'period', 'status': 'conflicting',
               'conflict': ['fixture-obs'], 'support': [], 'reasoning_summary': 'Synthetic recorded conflict'}]}}
    with store.tx() as db:
        store.put(db, 'run', run)
        case['current_run_id'] = run['id']
        store.put(db, 'case', case)
    return run


@pytest.mark.parametrize('dimension', ['period', 'condition'])
def test_review_only_revision_preserves_model_conflict_and_original_run(service, dimension):
    c, store = service; case, _ = photo(c, new(c)); run = saved_current_conflict(store, case)
    original = digest(store.read('run', run['id']))
    before = c.get('/api/cases/'+case['id']+'/risk-triage').json()
    response = check(c, case, dimension, 'consistent'); assert response.status_code == 201
    case = response.json()['case']
