@pytest.mark.parametrize('with_model', [False, True])
def test_material_revert_does_not_reactivate_old_operator_assertion(service, with_model):
    c, store = service; case, _ = photo(c, new(c))
    if with_model:
        saved_current_conflict(store, case)
    case = check(c, case, 'period', 'consistent').json()['case']
    old_check = copy.deepcopy(case['risk_checks'][0])
    original = copy.deepcopy(case['catalogue'])
    for catalogue in (original | {'dimensions': 'Changed fixture material'}, original):
        response = c.patch('/api/cases/'+case['id']+'/catalogue',
            json=mut(case)|{'workflow': case['workflow'], 'catalogue': catalogue})
        assert response.status_code == 200
        case = response.json()
        triaged = c.get('/api/cases/'+case['id']+'/risk-triage').json()
        assert triaged['dimensions'][0]['state'] == 'unknown'
        assert triaged['indices']['coverage_weight'] == 0
        assert old_check['id'] not in triaged['current_material_check_ids']
    assert case['risk_checks'] == [old_check]
    # A new check may evaluate its own dimension; it cannot reactivate the historical period check.
    case = check(c, case, 'condition', 'consistent').json()['case']
    triaged = c.get('/api/cases/'+case['id']+'/risk-triage').json()
    assert triaged['dimensions'][0]['state'] == 'unknown'
    assert triaged['dimensions'][4]['state'] == 'consistent'
    assert triaged['indices']['coverage_weight'] == 15
    assert old_check['id'] not in triaged['current_material_check_ids']
    assert case['risk_checks'][0] == old_check
